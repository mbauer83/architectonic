"""arch-init does not refuse a clone whose only changes are the include files it wrote itself.

Regression: arch-init regenerates the generated include files of both repositories on every run. In a
clone of an enterprise repository whose committed includes lag the ontology, the first run left them
modified, and the second run's working-tree check refused the clone ("has uncommitted changes"). Every
container restart after the first therefore crash-looped, and so did every start after a restore.
"""

from __future__ import annotations

import subprocess
from pathlib import Path

from src.infrastructure.rendering.generate_static_includes import (
    STATIC_INCLUDE_NAMES,
    generate_static_includes,
    static_include_paths,
)
from src.infrastructure.workspace import workspace_init


def _git(repo: Path, *args: str) -> None:
    subprocess.run(["git", *args], cwd=repo, check=True, capture_output=True)


def _clone_with_stale_includes(tmp_path: Path) -> Path:
    repo = tmp_path / "enterprise"
    (repo / "model").mkdir(parents=True)
    (repo / "model" / "README.md").write_text("model\n", encoding="utf-8")
    catalog = repo / "diagram-catalog"
    catalog.mkdir()
    for name in STATIC_INCLUDE_NAMES[:2]:  # an older release generated two of the three
        (catalog / name).write_text("' generated by an older release\n", encoding="utf-8")
    _git(repo, "init", "-q")
    _git(repo, "add", "-A")
    _git(repo, "-c", "user.name=t", "-c", "user.email=t@example.invalid", "commit", "-q", "-m", "initial")
    return repo


def test_the_paths_named_are_the_files_the_generator_writes(tmp_path: Path) -> None:
    repo = tmp_path / "repo"
    repo.mkdir()

    generate_static_includes(repo)

    written = {str(path.relative_to(repo)) for path in repo.rglob("*") if path.is_file()}
    assert written == set(static_include_paths())


def test_regenerated_includes_alone_do_not_make_the_clone_dirty(tmp_path: Path) -> None:
    repo = _clone_with_stale_includes(tmp_path)

    generate_static_includes(repo)  # modifies two tracked files, adds one untracked

    assert workspace_init._is_dirty(repo) is False


def test_any_other_change_still_does(tmp_path: Path) -> None:
    repo = _clone_with_stale_includes(tmp_path)
    generate_static_includes(repo)

    (repo / "model" / "README.md").write_text("edited\n", encoding="utf-8")

    assert workspace_init._is_dirty(repo) is True
